"""
Point-by-point correctness check of the spatial partitioning methods.

For each dataset, records the cell that every point is assigned to by

  grid join  ST_SquareGrid over the extent of the points, joined with ST_Intersects
  lateral    CROSS JOIN LATERAL ST_SquareGrid(L, geom) WHERE ST_Intersects(...)
  unfiltered the lateral join without the ST_Intersects predicate
  udf        hsql_spatial_partition(x, y, L)

and compares the assignments with each other and with the expected cell.
The datasets are generated by eval_vs_postgis.py with the same seeds as the
runtime benchmark. Results are explained in results/correctness_check.md.

It also checks the lateral join on points placed exactly on cell edges and
corners, which the generated datasets do not contain.

Usage (from repository root; needs psql on PATH and the PostGIS extension):
  python3 evaluation/spatial_partition/evaluation/check_equivalence.py
  python3 evaluation/spatial_partition/evaluation/check_equivalence.py --boundaries-only
"""

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import eval_vs_postgis as e  # noqa: E402

DB = "hsql_equiv_check"
# distribution, number of points, seed (as in the benchmark), cell side length in meters
DATASETS = [
    ("compact", 1000000, 0.13, 1000),
    ("skewed", 100000, 0.12, 1000),
    ("global", 100000, 0.12, 10000),
]
# Grid origin of hsql_spatial_partition (see space_partition.sql). It was the
# south-west corner of the Web Mercator plane, (-20037508.34, -20037508.34),
# when results/correctness_check.md was written; it is now (0, 0).
UDF_ORIGIN = 0.0


def diff_count(a, b):
    """SQL counting the rows that are in exactly one of the two queries."""
    return f"(SELECT count(*) FROM (({a} EXCEPT {b}) UNION ALL ({b} EXCEPT {a})) AS s)"


def check(dist, n, seed, cell):
    e.create_table(DB, dist, n, seed)
    t = e.table_name(dist, n)
    not_one = "(SELECT count(*) FROM (SELECT id FROM {0} GROUP BY id HAVING count(*) <> 1) AS s)"
    cells = "SELECT i, j, count(*) FROM {0} GROUP BY 1, 2"
    _, out, _ = e.psql(DB, f"""
    CREATE TEMP TABLE gj AS SELECT d.id, g.i, g.j FROM {t} d JOIN ST_SquareGrid({cell},
        ST_SetSRID(ST_EstimatedExtent('{t}', 'geom'), 3857)) g ON ST_Intersects(d.geom, g.geom);
    CREATE TEMP TABLE lj AS SELECT d.id, g.i, g.j FROM {t} d
        CROSS JOIN LATERAL ST_SquareGrid({cell}, d.geom) g WHERE ST_Intersects(d.geom, g.geom);
    CREATE TEMP TABLE lu AS SELECT d.id, g.i, g.j FROM {t} d
        CROSS JOIN LATERAL ST_SquareGrid({cell}, d.geom) g;
    -- Expected PostGIS square: its grid starts at the coordinate origin.
    CREATE TEMP TABLE truth AS
        SELECT id, floor(x / {cell})::int AS i, floor(y / {cell})::int AS j FROM {t};
    CREATE TEMP TABLE udf AS SELECT id, (hsql_spatial_partition(x, y, {cell})).* FROM {t};

    SELECT 'assignments: grid join ' || (SELECT count(*) FROM gj) || ', lateral ' || (SELECT count(*) FROM lj)
        || ', unfiltered lateral ' || (SELECT count(*) FROM lu) || ', udf ' || (SELECT count(*) FROM udf);
    SELECT 'points not assigned to exactly one square: grid join ' || {not_one.format('gj')}
        || ', lateral ' || {not_one.format('lj')} || ', unfiltered lateral ' || {not_one.format('lu')};
    SELECT 'points assigned differently by grid join and lateral: '
        || {diff_count('SELECT * FROM gj', 'SELECT * FROM lj')};
    SELECT 'points assigned differently from the expected square: grid join '
        || {diff_count('SELECT * FROM gj', 'SELECT * FROM truth')} || ', lateral '
        || {diff_count('SELECT * FROM lj', 'SELECT * FROM truth')};
    SELECT 'cells with a different point count in grid join and lateral: '
        || {diff_count(cells.format('gj'), cells.format('lj'))};
    SELECT 'udf: points outside the cell returned for them: ' || count(*)
    FROM udf u JOIN {t} d USING (id)
    WHERE NOT (d.x >= {UDF_ORIGIN} + u.x::float8 * {cell} AND d.x < {UDF_ORIGIN} + (u.x + 1)::float8 * {cell}
           AND d.y >= {UDF_ORIGIN} + u.y::float8 * {cell} AND d.y < {UDF_ORIGIN} + (u.y + 1)::float8 * {cell});
    SELECT 'non-empty cells: grid join ' || (SELECT count(*) FROM (SELECT DISTINCT i, j FROM gj) AS s)
        || ', lateral ' || (SELECT count(*) FROM (SELECT DISTINCT i, j FROM lj) AS s)
        || ', udf ' || (SELECT count(*) FROM (SELECT DISTINCT x, y FROM udf) AS s);
    """)
    print(f"== {dist}, {n} points, {cell} m cells\n{out}", flush=True)


def check_boundaries():
    """Squares assigned to hand-placed points inside, near, and on cell boundaries."""
    _, out, _ = e.psql(DB, """
    WITH pts(label, geom) AS (VALUES
      ('interior',            ST_SetSRID(ST_MakePoint(5400, 7500), 3857)),
      ('0.0001 m below edge', ST_SetSRID(ST_MakePoint(5999.9999, 7500), 3857)),
      ('on shared edge',      ST_SetSRID(ST_MakePoint(6000, 7500), 3857)),
      ('on corner',           ST_SetSRID(ST_MakePoint(6000, 8000), 3857)))
    SELECT p.label,
      (SELECT count(*) FROM ST_SquareGrid(1000, ST_MakeEnvelope(3000, 5000, 9000, 10000, 3857)) g
        WHERE ST_Intersects(p.geom, g.geom)) AS grid_join,
      (SELECT count(*) FROM ST_SquareGrid(1000, p.geom) g
        WHERE ST_Intersects(p.geom, g.geom)) AS lateral,
      (SELECT count(*) FROM ST_SquareGrid(1000, p.geom) g) AS unfiltered_lateral
    FROM pts p;
    """)
    print(f"== squares per boundary test point (label|grid join|lateral|unfiltered lateral)\n{out}")


def check_exact_boundaries(n=200000):
    """Lateral join on points lying exactly on cell edges and corners.

    Random points are placed on corners and edges of the 1 km grid across the
    Web Mercator plane; a few hand-placed points cover other cell sizes. For
    each point the lateral join must return exactly one square, the expected one.
    """
    lateral = """(SELECT count(*) AS n, bool_and(g.i = ei AND g.j = ej) AS ok
                  FROM ST_SquareGrid({cell}, p) g WHERE ST_Intersects(p, g.geom))"""
    summary = """SELECT '{label}: ' || count(*) || ' points, ' || count(*) FILTER (WHERE n <> 1)
        || ' not assigned to exactly one square, ' || count(*) FILTER (WHERE NOT ok)
        || ' assigned to a square other than the expected one'"""
    _, out, _ = e.psql(DB, f"""
    SELECT setseed(0.5);
    -- corners: both coordinates are multiples of the cell side length
    {summary.format(label='exact corners, 1 km cells')}
    FROM (SELECT ei, ej, ST_SetSRID(ST_MakePoint(ei * 1000.0, ej * 1000.0), 3857) AS p
          FROM (SELECT (random() * 40000 - 20000)::int AS ei, (random() * 18000 - 7000)::int AS ej
                FROM generate_series(1, {n})) r) q
    CROSS JOIN LATERAL {lateral.format(cell=1000)} l;
    -- vertical edges: x is a multiple of the cell side length, y is arbitrary
    {summary.format(label='exact vertical edges, 1 km cells')}
    FROM (SELECT ei, floor(y / 1000)::int AS ej, ST_SetSRID(ST_MakePoint(ei * 1000.0, y), 3857) AS p
          FROM (SELECT (random() * 40000 - 20000)::int AS ei, random() * 18000000 - 7000000 AS y
                FROM generate_series(1, {n})) r) q
    CROSS JOIN LATERAL {lateral.format(cell=1000)} l;
    -- horizontal edges: y is a multiple of the cell side length, x is arbitrary
    {summary.format(label='exact horizontal edges, 1 km cells')}
    FROM (SELECT floor(x / 1000)::int AS ei, ej, ST_SetSRID(ST_MakePoint(x, ej * 1000.0), 3857) AS p
          FROM (SELECT random() * 40000000 - 20000000 AS x, (random() * 18000 - 7000)::int AS ej
                FROM generate_series(1, {n})) r) q
    CROSS JOIN LATERAL {lateral.format(cell=1000)} l;
    -- hand-placed corners with other cell sizes
    SELECT label || ': ' || n || ' square(s), expected square ' || CASE WHEN ok THEN 'yes' ELSE 'no' END
    FROM (VALUES
        ('corner, 1500 m cells', 4434000::float8, 2442000::float8, 1500),
        ('corner, 250 m cells', 4433250, 2442750, 250),
        ('corner, 10 km cells, negative coordinates', -8240000, -2700000, 10000)) AS v(label, x, y, cell)
    CROSS JOIN LATERAL (SELECT floor(x / cell)::int AS ei, floor(y / cell)::int AS ej,
                               ST_SetSRID(ST_MakePoint(x, y), 3857) AS p) q
    CROSS JOIN LATERAL (SELECT count(*) AS n, bool_and(g.i = ei AND g.j = ej) AS ok
                        FROM ST_SquareGrid(cell, p) g WHERE ST_Intersects(p, g.geom)) l;
    """)
    print(f"== lateral join on points exactly on cell boundaries\n{out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--boundaries-only", action="store_true",
                    help="skip the dataset comparison and run only the boundary checks")
    args = ap.parse_args()

    subprocess.run(["dropdb", "--if-exists", DB], check=True, capture_output=True)
    subprocess.run(["createdb", DB], check=True)
    try:
        e.psql(DB, "CREATE EXTENSION postgis;")
        e.psql(DB, e.UDF_SQL.read_text())
        if not args.boundaries_only:
            for dataset in DATASETS:
                check(*dataset)
        check_boundaries()
        check_exact_boundaries()
    finally:
        subprocess.run(["dropdb", "--if-exists", DB], check=True)


if __name__ == "__main__":
    main()
